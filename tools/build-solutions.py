"""Assemble appendix G from the per-chapter solution fragments.

Each chapter's solutions live in `chapters/solutions/NN-slug.qmd`, written
beside the chapter so that the exercises and their answers share one author
and one data setup. Quarto's include shortcode is static, so this script
writes `chapters/96-solutions.qmd` with one include per fragment that exists,
in chapter order. Run it before a render whenever a solutions file is added:

    python tools/build-solutions.py

The fragments run as part of the appendix at render time, so every number in
a solution is computed, and a solution that stops running fails the render
rather than printing a stale answer.
"""
import io, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOL = os.path.join(ROOT, "chapters", "solutions")
OUT = os.path.join(ROOT, "chapters", "96-solutions.qmd")

HEAD = '''---
metadata:
  pagetitle: "Solutions to Exercises"
  description-meta: "Worked solutions to every chapter's exercises, computed on the same data."
---

# Solutions to Exercises {#sec-96-solutions}

Every chapter closes with exercises, and this appendix answers them. The
solutions are written beside the chapters and run on the same data, so each
number below is computed at render time rather than copied from a chapter; a
solution that stops running stops the render. Chapters are listed in order,
and a chapter absent from this appendix has no exercises yet.

<!-- Generated by tools/build-solutions.py from chapters/solutions/*.qmd.
     Do not edit by hand; add or change a fragment and rerun the script. -->

'''

frags = sorted(f for f in os.listdir(SOL) if re.match(r"^\d{2}-.*\.qmd$", f))
body = "\n".join("{{{{< include solutions/{} >}}}}\n".format(f) for f in frags)
io.open(OUT, "w", encoding="utf-8", newline="\n").write(HEAD + body)
print("wrote %s with %d fragments: %s" % (os.path.relpath(OUT, ROOT), len(frags),
                                          ", ".join(f[:2] for f in frags)))
